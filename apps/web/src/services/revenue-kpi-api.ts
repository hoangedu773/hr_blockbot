import type { RevenueKpiPeriod, RevenueKpiAssignment, RevenueKpiResult, RevenueKpiDashboard } from '@hr-blockbot/contracts';
import { requestJson } from './api';
const post = <T>(path: string, body: unknown) => requestJson<T>('/revenue-kpi' + path, { method: 'POST', body: JSON.stringify(body), headers: { 'Content-Type': 'application/json' } });
export const getRevenueKpiConfig = () => requestJson<{ enabled: boolean }>('/revenue-kpi/config');
export const listRevenueKpiPeriods = () => requestJson<{ items: RevenueKpiPeriod[] }>('/revenue-kpi/periods');
export const createRevenueKpiPeriod = (body: unknown) => post<RevenueKpiPeriod>('/periods', body);
export const openRevenueKpiPeriod = (p: string, body: unknown) => post<RevenueKpiPeriod>(`/periods/${p}/open`, body);
export const computeRevenueKpiPeriod = (p: string, body: unknown) => post<RevenueKpiPeriod>(`/periods/${p}/compute`, body);
export const closeRevenueKpiPeriod = (p: string, body: unknown) => post<RevenueKpiPeriod>(`/periods/${p}/close`, body);
export const listRevenueKpiAssignments = (p: string) => requestJson<{ items: RevenueKpiAssignment[] }>(`/revenue-kpi/periods/${p}/assignments`);
export const saveRevenueKpiAssignment = (body: unknown) => post<RevenueKpiAssignment>('/assignments', body);
const assignmentAction = (action: string) => (id: string, body: unknown) => post<RevenueKpiAssignment>(`/assignments/${id}/${action}`, body);
export const publishRevenueKpiAssignment = assignmentAction('publish');
export const acceptRevenueKpiAssignment = assignmentAction('accept');
export const refuseRevenueKpiAssignment = assignmentAction('refuse');
export const decideRevenueKpiAssignment = assignmentAction('hr-decision');
export const requestRevenueKpiAdjustment = assignmentAction('adjustment-request');
export const verifyRevenueKpiAdjustment = assignmentAction('adjustment-verify');
export const decideRevenueKpiAdjustment = assignmentAction('adjustment-decision');
export const proposeRevenueKpiTarget = assignmentAction('ai-proposal');
export const changeRevenueKpiResponsibility = assignmentAction('responsibility');
export const getRevenueKpiResult = (id: string) => requestJson<{ assignment: RevenueKpiAssignment; result: RevenueKpiResult | null }>(`/revenue-kpi/assignments/${id}/result`);
const resultAction = (action: string) => (id: string, body: unknown) => post<RevenueKpiResult>(`/results/${id}/${action}`, body);
export const submitRevenueKpiMissReason = resultAction('miss-reason');
export const reviewRevenueKpiReason = resultAction('review-reason');
export const confirmRevenueKpiResult = resultAction('confirm');
export const correctRevenueKpiResult = resultAction('correct');
export const getRevenueKpiDashboard = (period: string) => requestJson<RevenueKpiDashboard>(`/revenue-kpi/dashboard?period=${encodeURIComponent(period)}`);
